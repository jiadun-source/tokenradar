// Token Radar's model, version radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every other
// pre-token protocol the snapshot carries that can be ranked: the early rows the radar exists to find.
// A protocol is pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol);
// the live-token protocols are kept apart and shown with the market's own values, never mixed into the
// ranked board.
//
// Implied value is calibrated from the market itself, not from a fixed multiple. The snapshot's
// live-token protocols already trade, so each one prices its category: the median market-cap-to-TVL
// ratio of the live protocols in a category is what the market pays for a unit of TVL there. A
// pre-token protocol is worth its TVL at its category's ratio, adjusted for growth and maturity:
//
//   multiple   = median(mcap_usd / tvl_usd) over live protocols in the category
//                (fewer than 3 live comps: the all-category median instead; clamped to 0.02..2.0)
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied    = max(1, round(base x growthMult x maturity))
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard names
// the multiple and the number of live protocols that set it, so any row can be checked by hand.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

