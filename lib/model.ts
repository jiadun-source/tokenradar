/** Why the snapshot is not one this model can score. */
export class SnapshotError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'SnapshotError';
  }
}

const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** The median of a sorted array, or 0 when it is empty. */
function medianOf(sorted: number[]): number {
  if (sorted.length === 0) return 0;
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1 ? sorted[mid]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/**
 * Calibrate the market multiple from the snapshot's own live-token protocols. Centralised exchanges
 * are left out: their market cap prices a company, not a protocol's TVL. A category needs at least
 * `min_category_comps` live protocols to set its own multiple; a thinner category falls back to the
 * all-category median, so no row rests on one or two comparables.
 */
export function calibrate(snapshot: Snapshot, model: ModelConstants = MODEL): Calibration {
  const live = snapshot.protocols.filter(
    (p) => p.mcap_usd !== null && p.mcap_usd > 0 && p.tvl_usd > 0 && p.category !== 'CEX',
  );
  const all = live.map((p) => p.mcap_usd! / p.tvl_usd).sort((a, b) => a - b);
  const overall = Math.min(model.ratio_cap, Math.max(model.ratio_floor, medianOf(all)));
  const byCategory = new Map<string, number[]>();
  for (const p of live) {
    const cat = p.category ?? 'Other';
    if (!byCategory.has(cat)) byCategory.set(cat, []);
    byCategory.get(cat)!.push(p.mcap_usd! / p.tvl_usd);
  }
  const ratios = new Map<string, number>();
  const table: CategoryRatio[] = [];
  for (const [cat, rs] of [...byCategory.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    rs.sort((a, b) => a - b);
    const med = medianOf(rs);
    const ratio =
      rs.length >= model.min_category_comps
        ? Math.min(model.ratio_cap, Math.max(model.ratio_floor, med))
        : overall;
    ratios.set(cat, ratio);
    table.push({ category: cat, ratio: Math.round(ratio * 1000) / 1000, comps: rs.length });
  }
  return { byCategory: ratios, overall, table };
}

/** The multiple a protocol's category pays, and how many live protocols set it. */
function multipleFor(p: SnapshotProtocol, cal: Calibration, model: ModelConstants): { ratio: number; comps: number } {
  const cat = p.category ?? 'Other';
  const ratio = cal.byCategory.get(cat);
  if (ratio === undefined) return { ratio: cal.overall, comps: 0 };
  const entry = cal.table.find((t) => t.category === cat);
  const comps = entry === undefined ? 0 : entry.comps;
  if (comps < model.min_category_comps) return { ratio: cal.overall, comps };
  return { ratio, comps };
}

/** The three multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(
  protocol: SnapshotProtocol,
  asOf: string,
  cal: Calibration,
  model: ModelConstants,
): { implied: number; ratio: number; comps: number; growthPct: number; growthMult: number; maturityMult: number; age: number | null } {
  const age = ageDays(asOf, protocol.listed_at);
  const { ratio, comps } = multipleFor(protocol, cal, model);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? model.unknown_age_days;
  const maturityMult =
    model.maturity_floor +
    (Math.min(Math.max(ageForModel, 0), model.maturity_days) / model.maturity_days) * model.maturity_range;
  const base = protocol.tvl_usd * ratio;
  const implied = Math.max(1, Math.round(base * growthMult * maturityMult));
  return { implied, ratio, comps, growthPct, growthMult, maturityMult, age };
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;

/** Categories whose product is a wrapped, staked or bridged form of a token that already trades. */
const WRAPPED_PRODUCT_CATEGORIES = new Set([
  'Bridge',
  'Canonical Bridge',
  'Liquid Staking',
  'Liquid Restaking',
  'Restaked BTC',
  'CEX',
]);

/** A whole word in the name that marks a wrapped or staked product. */
const WRAPPED_WORD = /\b(wrapped|staked|staking)\b/i;

/** An exchange whose name at the start marks the protocol as its product. */
const EXCHANGE_PREFIX = /^(Binance|Coinbase|Bybit|Kraken|Bitget|OKX|Bitfinex|Gemini)\b/i;

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/**
 * Whether a protocol is one the board may rank: pre-token, and not a wrapped, staked or bridged
 * product of a protocol whose token already trades. This is the watchlist's own rule, minus its TVL
 * floor: the board ranks protocols below the floor too, but it never ranks a wrapped product as if
 * its token were still to come. WBTC, Binance staked ETH and USDT0 are off the watchlist for exactly
 * this reason, and they stay off this board.
 */
export function isRankable(p: SnapshotProtocol): boolean {
  if (!isPreToken(p)) return false;
  if (p.category !== null && WRAPPED_PRODUCT_CATEGORIES.has(p.category)) return false;
  if (VERSIONED.test(p.name)) return false;
  if (WRAPPED_WORD.test(p.name)) return false;
  if (EXCHANGE_PREFIX.test(p.name)) return false;
  return true;
}

/** The snapshot's protocol by slug. */
function bySlug(protocols: SnapshotProtocol[]): Map<string, SnapshotProtocol> {
  return new Map(protocols.map((p) => [p.slug, p]));
}

/** The protocols the board ranks, strongest first, with ranks 1..n. */
export function buildBoard(snapshot: Snapshot, model: ModelConstants = MODEL): BoardRow[] {
  const cal = calibrate(snapshot, model);
  const index = bySlug(snapshot.protocols);
  const chosen = new Map<string, SnapshotProtocol>();
  // The watchlist is the floor: every slug, even one the snapshot no longer carries (it cannot, but
  // the board's coverage is the gate's row and is never gambled on a missing record).
  for (const slug of snapshot.watchlist) {
    const p = index.get(slug);
    if (p !== undefined) chosen.set(slug, p);
  }
  // The early radar: every other pre-token protocol the snapshot can rank, not just the largest.
  // The board is a radar, not a shortlist: a small protocol the model scores highly belongs on it.
  for (const p of snapshot.protocols) {
    if (!chosen.has(p.slug) && isRankable(p)) chosen.set(p.slug, p);
  }

  const scored = [...chosen.values()].map((p) => {
    const v = impliedValue(p, snapshot.as_of, cal, model);
    return { p, ...v };
  });
  scored.sort((a, b) => b.implied - a.implied || (a.p.slug < b.p.slug ? -1 : a.p.slug > b.p.slug ? 1 : 0));
  return scored.map((s, i) => ({
    rank: i + 1,
    slug: s.p.slug,
    name: s.p.name,
    category: s.p.category,
    chains: s.p.chains,
    tvl_usd: s.p.tvl_usd,
    change_7d: s.p.change_7d,
    mcap_usd: s.p.mcap_usd,
    listed_at: s.p.listed_at,
    gecko_id: s.p.gecko_id,
    symbol: s.p.symbol,
    token_status: 'pre-token',
    age_days: s.age,
    implied_value_usd: s.implied,
    model: {
      category_multiple: s.ratio,
      category_comps: s.comps,
      growth_pct: s.growthPct,
      growth_multiplier: round4(s.growthMult),
      maturity_multiplier: round4(s.maturityMult),
      age_days: s.age,
    },
    farm_steps: farmSteps(s.p, s.age).map(stepText),
  }));
}

const round4 = (n: number): number => Math.round(n * 1e4) / 1e4;

/** A step as one string: its action, then its cost and time, within the gate's 20..600 characters. */
export function stepText(step: FarmStep): string {
  let s = `${step.text} Cost: ${step.cost}. Time: ${step.time}.`;
  if (s.length > 600) s = `${s.slice(0, 596)}...`;
  if (s.length < 20) s = `${s} Hold the position and check the protocol's own page.`;
  return s;
}

/** The first chain a protocol names, or a neutral phrase. */
function chainOf(p: SnapshotProtocol): string {
  return p.chains.length > 0 ? p.chains[0]! : 'its main chain';
}

/** How much capital one farm position needs, from the protocol's own TVL. */
function capitalFor(p: SnapshotProtocol): number {
  if (p.tvl_usd >= 5_000_000_000) return 250;
  if (p.tvl_usd >= 1_000_000_000) return 150;
  if (p.tvl_usd >= 100_000_000) return 100;
  return 50;
}

/** What one transaction costs on the protocol's first chain: mainnet is dear, rollups are cheap. */
function gasFor(chain: string): string {
  const c = chain.toLowerCase();
  if (c.includes('ethereum')) return 'about $6 of gas';
  if (c.includes('bitcoin') || c.includes('solana')) return 'under $1 of gas';
  return 'about $1 of gas';
}

/** How long to hold, from the protocol's age: younger protocols get a longer qualifying window. */
function holdDaysFor(age: number | null): number {
  if (age === null) return 30;
  if (age < 180) return 60;
  if (age < 365) return 45;
  return 30;
}

/** The category's setup action and its weekly action, in the words a farmer can follow. */
function actionsFor(p: SnapshotProtocol, capital: number, chain: string): { setup: string; weekly: string } {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) {
    return {
      setup: `Supply $${capital} of USDC to ${name} on ${chain}, then borrow a small amount against it so the position shows both sides.`,
      weekly: 'a supply top-up, a borrow or a repayment',
    };
  }
  if (c.includes('dex') || c.includes('leveraged farm')) {
    return {
      setup: `Swap $${capital / 2} of USDC for the pool's other asset on ${name} on ${chain}, then provide $${capital} of liquidity to its main pool.`,
      weekly: 'a swap or a liquidity top-up',
    };
  }
  if (c.includes('yield') || c.includes('vault')) {
    return {
      setup: `Deposit $${capital} of USDC into ${name}'s main vault on ${chain} and keep the receipt tokens.`,
      weekly: 'a deposit or a vault rebalance',
    };
  }
  if (c.includes('bridge')) {
    return {
      setup: `Bridge $${capital} of USDC to ${chain} through ${name}, then use the bridged funds once inside its app.`,
      weekly: 'a bridge or a swap on the destination chain',
    };
  }
  if (c.includes('staking') || c.includes('restak')) {
    return {
      setup: `Stake $${capital} of the chain's staking asset through ${name} on ${chain} and keep the receipt token in the same wallet.`,
      weekly: 'a restake or a claim of the staking rewards',
    };
  }
  if (c.includes('perpetual') || c.includes('derivative')) {
    return {
      setup: `Deposit $${capital} of USDC as margin on ${name} on ${chain} and open one small hedge that stays open a week.`,
      weekly: 'a small trade or a margin top-up',
    };
  }
  if (c.includes('prediction')) {
    return {
      setup: `Fund $${capital} on ${name} on ${chain} and place one market position on an outcome that settles after a week.`,
      weekly: 'a market position or a settlement claim',
    };
  }
  if (c.includes('curator') || c.includes('allocator')) {
    return {
      setup: `Deposit $${capital} into a ${name} vault on ${chain} and keep the vault shares in the same wallet.`,
      weekly: 'a deposit or a vault share top-up',
    };
  }
  if (c.includes('stable')) {
    return {
      setup: `Mint or deposit $${capital} of the stable asset through ${name} on ${chain} and hold it in the farming wallet.`,
      weekly: 'a mint, a deposit or a redemption',
    };
  }
  if (c.includes('rwa')) {
    return {
      setup: `Mint $${capital} of the protocol's yield-bearing asset on ${chain} through ${name} and hold it.`,
      weekly: 'a mint or a yield claim',
    };
  }
  if (c.includes('insurance')) {
    return {
      setup: `Buy $${capital} of cover from ${name} on ${chain} and keep the policy active for the whole farming window.`,
      weekly: 'a cover top-up or a policy renewal',
    };
  }
  return {
    setup: `Deposit $${capital} of USDC into ${name} on ${chain} and keep the position open.`,
    weekly: 'a deposit, a swap or a vote',
  };
}

/**
 * A protocol's farm plan: six steps, each an action with a cost and a time. The plan is derived from
 * the protocol's own record (category, chains, TVL, age), never from a hand-written list of names.
 */
export function farmSteps(p: SnapshotProtocol, age: number | null): FarmStep[] {
  const chain = chainOf(p);
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  const gas = gasFor(chain);
  const { setup, weekly } = actionsFor(p, capital, chain);
  return [
    {
      text: `Use a fresh wallet that holds only the funds you plan to farm, and keep its seed phrase offline.`,
      cost: 'under $3 of gas for the first transaction',
      time: '5 minutes',
    },
    {
      text: setup,
      cost: `$${capital} of capital and ${gas}`,
      time: '15 minutes to set up',
    },
    {
      text: `Make one qualifying action each week, such as ${weekly}, so the wallet shows repeated use.`,
      cost: 'about $2 of gas a week',
      time: '10 minutes a week',
    },
    {
      text: `Hold the position for at least ${hold} days so the activity is counted in more than one snapshot.`,
      cost: `the $${capital} stays in the position`,
      time: `${hold} days`,
    },
    {
      text: `Before you withdraw, open the protocol's own points or rewards page and claim only from the link it publishes.`,
      cost: 'no fee to check, and never pay to claim',
      time: '10 minutes',
    },
    {
      text: `Write the wallet, the dates and every transaction in a farm log so you can repeat the position or unwind it.`,
      cost: 'nothing but the log',
      time: '5 minutes',
    },
  ];
}

/** The live-token protocols, by market cap, for the dashboard's Live token view. */
export function liveRows(snapshot: Snapshot): LiveRow[] {
  return snapshot.protocols
    .filter((p) => !isPreToken(p) && p.category !== 'CEX')
    .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0) || b.tvl_usd - a.tvl_usd)
    .slice(0, LIVE_ROWS)
    .map((p) => ({
      slug: p.slug,
      name: p.name,
      category: p.category,
      chains: p.chains,
      tvl_usd: p.tvl_usd,
      mcap_usd: p.mcap_usd,
      change_7d: p.change_7d,
    }));
}

